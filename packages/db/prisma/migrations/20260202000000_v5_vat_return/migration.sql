-- V5 / milestone V5-M1: the VAT return (DEC-090). Additive. A return is one client's VAT period, tied to the M4b workpaper by a fingerprint;
-- its events are append-only. The client's approval freezes the return (content and SHA-256, written once) and locks the period: from then on
-- no journal line may carry a tax point inside it. Nothing is filed here (V5-M2; DEC-082, DEC-086).

CREATE TABLE "vat_return" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "organisation_id" UUID NOT NULL,
    "company_id" UUID NOT NULL,
    "period_from" DATE NOT NULL,
    "period_to" DATE NOT NULL,
    "obligation_id" UUID,
    "created_by_user_id" UUID NOT NULL,
    "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "locked_at" TIMESTAMPTZ(3),
    "locked_by_user_id" UUID,
    "approved_fingerprint" TEXT,
    "approved_content" JSONB,
    CONSTRAINT "vat_return_pkey" PRIMARY KEY ("id"),
    CONSTRAINT vat_return_period_ck CHECK (period_from <= period_to),
    CONSTRAINT vat_return_lock_ck CHECK ((locked_at IS NULL AND locked_by_user_id IS NULL AND approved_fingerprint IS NULL AND approved_content IS NULL)
                                         OR (locked_at IS NOT NULL AND locked_by_user_id IS NOT NULL AND approved_fingerprint ~ '^[0-9a-f]{64}$' AND approved_content IS NOT NULL))
);
CREATE UNIQUE INDEX "vat_return_organisation_id_id_key" ON "vat_return"("organisation_id", "id");
CREATE UNIQUE INDEX "vat_return_period_key" ON "vat_return"("organisation_id", "company_id", "period_from");
CREATE INDEX "vat_return_locked_idx" ON "vat_return"("organisation_id", "company_id", "period_from", "period_to") WHERE locked_at IS NOT NULL;
ALTER TABLE "vat_return" ADD CONSTRAINT "vat_return_company_fkey" FOREIGN KEY ("organisation_id", "company_id") REFERENCES "company"("organisation_id", "id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "vat_return" ADD CONSTRAINT "vat_return_obligation_fkey" FOREIGN KEY ("organisation_id", "obligation_id") REFERENCES "compliance_obligation"("organisation_id", "id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "vat_return" ADD CONSTRAINT "vat_return_created_by_fkey" FOREIGN KEY ("created_by_user_id") REFERENCES "user"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "vat_return" ADD CONSTRAINT "vat_return_locked_by_fkey" FOREIGN KEY ("locked_by_user_id") REFERENCES "user"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- What a return is never changes; the lock (with the approved content) is written once and never removed.
CREATE OR REPLACE FUNCTION vat_return_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.locked_at IS NOT NULL THEN RAISE EXCEPTION 'a VAT return starts unlocked' USING ERRCODE = '23514'; END IF;
    RETURN NEW;
  END IF;
  IF NEW.id <> OLD.id OR NEW.organisation_id <> OLD.organisation_id OR NEW.company_id <> OLD.company_id OR NEW.period_from <> OLD.period_from OR NEW.period_to <> OLD.period_to
     OR NEW.obligation_id IS DISTINCT FROM OLD.obligation_id OR NEW.created_by_user_id <> OLD.created_by_user_id OR NEW.created_at <> OLD.created_at THEN
    RAISE EXCEPTION 'what a VAT return is cannot change' USING ERRCODE = '42501';
  END IF;
  IF OLD.locked_at IS NOT NULL THEN RAISE EXCEPTION 'an approved VAT return is frozen' USING ERRCODE = '42501'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER vat_return_guard_trg BEFORE INSERT OR UPDATE ON vat_return FOR EACH ROW EXECUTE FUNCTION vat_return_guard();
CREATE TRIGGER vat_return_no_delete BEFORE DELETE ON vat_return FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER vat_return_no_truncate BEFORE TRUNCATE ON vat_return FOR EACH STATEMENT EXECUTE FUNCTION forbid_mutation();

-- ───────── Events: append-only, each on the fingerprint it was made on ─────────
CREATE TABLE "vat_return_event" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "seq" INTEGER GENERATED BY DEFAULT AS IDENTITY,
    "organisation_id" UUID NOT NULL,
    "company_id" UUID NOT NULL,
    "vat_return_id" UUID NOT NULL,
    "kind" TEXT NOT NULL,
    "fingerprint" TEXT NOT NULL,
    "flag_key" TEXT,
    "note" TEXT,
    "approver_contact_id" UUID,
    "approved_on" DATE,
    "evidence_document_id" UUID,
    "by_user_id" UUID NOT NULL,
    "at" TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT "vat_return_event_pkey" PRIMARY KEY ("id"),
    CONSTRAINT vre_kind_ck CHECK (kind IN ('PREPARED','FLAG_EXPLAINED','REVIEWED','CLIENT_APPROVED')),
    CONSTRAINT vre_fingerprint_ck CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
    CONSTRAINT vre_note_ck CHECK (note IS NULL OR char_length(btrim(note)) BETWEEN 1 AND 2000),
    CONSTRAINT vre_flag_ck CHECK ((kind = 'FLAG_EXPLAINED') = (flag_key IS NOT NULL) AND (kind <> 'FLAG_EXPLAINED' OR char_length(btrim(coalesce(note, ''))) >= 10)),
    CONSTRAINT vre_approval_ck CHECK ((kind = 'CLIENT_APPROVED') = (approver_contact_id IS NOT NULL AND approved_on IS NOT NULL AND evidence_document_id IS NOT NULL)
                                      AND (kind = 'CLIENT_APPROVED' OR (approver_contact_id IS NULL AND approved_on IS NULL AND evidence_document_id IS NULL)))
);
CREATE UNIQUE INDEX "vat_return_event_seq_key" ON "vat_return_event"("seq");
CREATE INDEX "vat_return_event_return_idx" ON "vat_return_event"("organisation_id", "vat_return_id", "seq");
ALTER TABLE "vat_return_event" ADD CONSTRAINT "vre_return_fkey" FOREIGN KEY ("organisation_id", "vat_return_id") REFERENCES "vat_return"("organisation_id", "id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "vat_return_event" ADD CONSTRAINT "vre_company_fkey" FOREIGN KEY ("organisation_id", "company_id") REFERENCES "company"("organisation_id", "id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "vat_return_event" ADD CONSTRAINT "vre_contact_fkey" FOREIGN KEY ("organisation_id", "approver_contact_id") REFERENCES "contact"("organisation_id", "id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "vat_return_event" ADD CONSTRAINT "vre_evidence_fkey" FOREIGN KEY ("evidence_document_id") REFERENCES "document"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "vat_return_event" ADD CONSTRAINT "vre_by_fkey" FOREIGN KEY ("by_user_id") REFERENCES "user"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- The reviewer is not the person of the latest preparation on the same fingerprint (second person; the service says so first).
CREATE OR REPLACE FUNCTION vat_return_event_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.kind = 'REVIEWED' AND EXISTS (SELECT 1 FROM vat_return_event p WHERE p.organisation_id = NEW.organisation_id AND p.vat_return_id = NEW.vat_return_id
       AND p.kind = 'PREPARED' AND p.seq = (SELECT max(q.seq) FROM vat_return_event q WHERE q.organisation_id = NEW.organisation_id AND q.vat_return_id = NEW.vat_return_id AND q.kind = 'PREPARED')
       AND p.by_user_id = NEW.by_user_id) THEN
    RAISE EXCEPTION 'a VAT return is reviewed by someone other than the person who prepared it' USING ERRCODE = '42501';
  END IF;
  IF EXISTS (SELECT 1 FROM vat_return r WHERE r.organisation_id = NEW.organisation_id AND r.id = NEW.vat_return_id AND (r.locked_at IS NOT NULL OR r.company_id <> NEW.company_id)) THEN
    RAISE EXCEPTION 'an approved VAT return takes no further events' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER vat_return_event_guard_trg BEFORE INSERT ON vat_return_event FOR EACH ROW EXECUTE FUNCTION vat_return_event_guard();
CREATE TRIGGER vat_return_event_no_update BEFORE UPDATE ON vat_return_event FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER vat_return_event_no_delete BEFORE DELETE ON vat_return_event FOR EACH ROW EXECUTE FUNCTION forbid_mutation();
CREATE TRIGGER vat_return_event_no_truncate BEFORE TRUNCATE ON vat_return_event FOR EACH STATEMENT EXECUTE FUNCTION forbid_mutation();

-- ───────── The period lock: no VAT line with a tax point inside an approved return's period ─────────
CREATE OR REPLACE FUNCTION journal_line_vat_period_lock() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.tax_point IS NOT NULL AND EXISTS (SELECT 1 FROM vat_return r WHERE r.organisation_id = NEW.organisation_id AND r.company_id = NEW.company_id
       AND r.locked_at IS NOT NULL AND NEW.tax_point BETWEEN r.period_from AND r.period_to) THEN
    RAISE EXCEPTION 'vat_period_locked: the VAT return for the period containing % was approved; record the correction in a later return', NEW.tax_point USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;
-- named to run before the ledger's insert guard (BEFORE triggers run in name order), so a line in a locked period is refused with this reason
CREATE TRIGGER jl_vat_period_lock_trg BEFORE INSERT ON journal_line FOR EACH ROW EXECUTE FUNCTION journal_line_vat_period_lock();

