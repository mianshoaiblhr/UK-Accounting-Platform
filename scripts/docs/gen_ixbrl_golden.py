#!/usr/bin/env python3
"""Writes docs/architecture/v3-m2-golden-tagging.xlsx from docs/architecture/v3-m2-sample-ixbrl.xhtml: every context and every tagged fact of the
sample document (V3-M2, DEC-094), with the figure the approved package states for it and a formula that compares them. The sample is the
document tests/api/ixbrl-document.test.ts generates for the synthetic approved year (the V2-M6c golden) with a synthetic taxonomy version;
its concepts are test fixtures, not the FRC taxonomy. Usage: python3 scripts/docs/gen_ixbrl_golden.py (needs openpyxl)."""
import pathlib
import xml.etree.ElementTree as ET
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

root = pathlib.Path(__file__).resolve().parents[2]
SRC = root / "docs/architecture/v3-m2-sample-ixbrl.xhtml"
OUT = root / "docs/architecture/v3-m2-golden-tagging.xlsx"
NS = {"ix": "http://www.xbrl.org/2013/inlineXBRL", "xbrli": "http://www.xbrl.org/2003/instance", "xbrldi": "http://xbrl.org/2006/xbrldi"}
# what the approved package of the golden year states (tests/golden/v2-m6c-approval.json and the V2-M1 synthetic lines), by concept
EXPECTED = {"core:Turnover": "1200.00", "core:Depreciation": "1200.00", "core:ProfitLoss": "0.00", "core:FixedAssets": "2400.00", "core:Creditors": "0.00",
            "core:NetAssets": "10000.00", "core:Equity": "10000.00", "bus:EntityName": "Golden Approval Ltd", "bus:RegisteredNumber": "01234567",
            "bus:PeriodStart": "2025-01-01", "bus:PeriodEnd": "2025-12-31", "bus:BalanceSheetDate": "2025-12-31", "core:SigningDirector": "Synthetic Director",
            "core:ApprovalDate": "2026-03-16", "core:AverageEmployees": "1"}
HEAD, EXP = PatternFill("solid", fgColor="1F3A5F"), PatternFill("solid", fgColor="E8F1E4")
BOX = Border(*(Side(style="thin", color="BFBFBF"),) * 4)

doc = ET.parse(SRC).getroot()
contexts = {}
for c in doc.iter(f"{{{NS['xbrli']}}}context"):
    p = c.find("xbrli:period", NS)
    period = p.findtext("xbrli:instant", namespaces=NS) or f'{p.findtext("xbrli:startDate", namespaces=NS)} to {p.findtext("xbrli:endDate", namespaces=NS)}'
    dims = "; ".join(f'{m.get("dimension")} = {m.text}' for m in c.iter(f"{{{NS['xbrldi']}}}explicitMember"))
    ident = c.find("xbrli:entity/xbrli:identifier", NS)
    contexts[c.get("id")] = (period, dims, f'{ident.get("scheme")} {ident.text}')
facts = []
for tag in ("nonFraction", "nonNumeric"):
    for f in doc.iter(f"{{{NS['ix']}}}{tag}"):
        facts.append((f.get("name"), f.get("contextRef"), f.get("unitRef") or "", f.get("decimals") or "", f.get("sign") or "", "".join(f.itertext()), tag))

wb = Workbook()
ab = wb.active
ab.title = "About"
for r in [("V3-M2 golden tagging: the iXBRL document of the synthetic approved year (DEC-094)",), ("",),
          ("Source", "docs/architecture/v3-m2-sample-ixbrl.xhtml, generated by tests/api/ixbrl-document.test.ts"),
          ("Status", "FOR REVIEW by the named accountant. The concepts are synthetic test fixtures, not the FRC taxonomy; the real mapping is verified in the platform (worksheet, sheet 'iXBRL mapping')"),
          ("What to check", "That every tagged figure equals the approved accounts, with the right period (duration for the year, instant at the year end) and dimension"),
          ("Not checked here", "Schema and taxonomy validity: a go-live step with the FRC taxonomy files and an external validator (DEC-094)")]:
    ab.append(r)
ab["A1"].font = Font(bold=True, size=13)
ab.column_dimensions["A"].width, ab.column_dimensions["B"].width = 18, 120

def sheet(name, headers, widths, rows):
    ws = wb.create_sheet(name)
    for i, (h, w) in enumerate(zip(headers, widths), start=1):
        c = ws.cell(row=1, column=i, value=h)
        c.font, c.fill, c.border = Font(bold=True, color="FFFFFF"), HEAD, BOX
        ws.column_dimensions[get_column_letter(i)].width = w
    for r in rows:
        ws.append(r)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.border, c.alignment = BOX, Alignment(wrap_text=True, vertical="top")
    return ws

sheet("Contexts", ["Id", "Period", "Dimensions", "Entity identifier"], [8, 28, 60, 50], [(k, *v) for k, v in contexts.items()])
rows = []
for n, (name, ctx, unit, dec, sign, shown, tag) in enumerate(facts, start=2):
    period, dims, _ = contexts[ctx]
    if tag == "nonFraction":
        value = f'=IF(H{n}="-",-1,1)*VALUE(SUBSTITUTE(I{n},",",""))'
        expected = float(EXPECTED[name]) if name in EXPECTED else None
        agrees = f"=ROUND(J{n}-K{n},2)=0"
    else:
        value, expected, agrees = f"=I{n}", EXPECTED.get(name), f'=J{n}=K{n}'
    rows.append((name, ctx, period, dims, unit, dec, tag, sign, shown, value, expected, agrees))
ws = sheet("Facts", ["Concept", "Context", "Period", "Dimensions", "Unit", "Decimals", "Kind", "Sign", "Shown", "Value", "Expected (package)", "Agrees"],
           [26, 8, 24, 44, 8, 9, 12, 6, 22, 14, 22, 9], rows)
for r in range(2, len(rows) + 2):
    ws.cell(row=r, column=11).fill = EXP
so = sheet("Sign-off", ["Reviewer", "Date", "Agrees (yes/no)", "Notes"], [28, 14, 16, 70], [("", "", "", "")])
wb.save(OUT)
print(f"wrote {OUT.relative_to(root)} ({len(facts)} facts, {len(contexts)} contexts)")
